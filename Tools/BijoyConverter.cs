        private const string C = "[\u0995-\u09B9\u09DC-\u09DF\u09CE]";          // ব্যঞ্জনবর্ণ
        private const string Cluster = "(?:" + C + "\u09CD)*" + C;              // যুক্তবর্ণসহ

        // ি ে ৈ কার বিজয়ে ব্যঞ্জনের আগে বসে, ইউনিকোডে পরে
        private static readonly Regex PreKar = new Regex("([\u09BF\u09C7\u09C8])(" + Cluster + ")", RegexOptions.Compiled);
        // রেফ (©) বিজয়ে ব্যঞ্জন+কারের পরে বসে, ইউনিকোডে আগে (র্)
        private static readonly Regex Reph = new Regex("(" + Cluster + "[\u09BE-\u09CC\u09D7]*)©", RegexOptions.Compiled);

        private static readonly Regex ChandraBefore = new Regex("\u0981([\u09BE\u09C0-\u09C4\u09D7])", RegexOptions.Compiled);

        public static string Convert(string input)
        {
            if (string.IsNullOrEmpty(input)) return input;

            string s = input;
            foreach (string[] m in Multi) s = s.Replace(m[0], m[1]);

            StringBuilder sb = new StringBuilder(s.Length + 8);
            foreach (char ch in s)
            {
                string r;
                if (Single.TryGetValue(ch, out r)) sb.Append(r); else sb.Append(ch);
            }
            s = sb.ToString();

            s = s.Replace("\u09CD\u09CD", "\u09CD");   // অর্ধ-বর্ণ + ফলা মিলে দুই হসন্ত হলে একটি রাখা (যেমন ম্ + ্র)
            // ড় ঢ় য় যদি ভেঙে (ড + ়) এসে থাকে, জোড়া লাগিয়ে নেওয়া
            s = s.Replace("\u09A1\u09BC", "\u09DC").Replace("\u09A2\u09BC", "\u09DD").Replace("\u09AF\u09BC", "\u09DF");
            // বিজয়ে ঁ কারের আগে বসে (Muv), ইউনিকোডে কারের পরে (গাঁ)
            s = ChandraBefore.Replace(s, "$1\u0981");
            s = PreKar.Replace(s, "$2$1");
            s = s.Replace("\u09C7\u09BE", "\u09CB");   // ে + া = ো
            s = s.Replace("\u09C7\u09D7", "\u09CC");   // ে + ৗ = ৌ
            s = Reph.Replace(s, "\u09B0\u09CD$1");     // রেফ
            // মোঃ / মোছাঃ / মোসাঃ — অনেকে ঃ এর জায়গায় কোলন (:) টাইপ করে; আর ঃ এর আগের ফাঁকা সরানো
            s = Regex.Replace(s, "(\u09AE\u09CB(?:\u099B\u09BE|\u09B8\u09BE)?):", "$1\u0983");
            s = Regex.Replace(s, "(?<=[\u0980-\u09FF])[ \u00A0]+\u0983", "\u0983");
            return s;
        }

        /// <summary>টেক্সটে আগে থেকেই ইউনিকোড বাংলা অক্ষর আছে কিনা (থাকলে আবার কনভার্ট করা হবে না)</summary>
        public static bool ContainsBengali(string s)
        {
            foreach (char c in s)
                if (c >= '\u0980' && c <= '\u09FF') return true;
            return false;
        }

        /// <summary>কনভার্টের পরেও যে চিহ্নগুলো রূপান্তর হয়নি (ম্যাপিং নেই) সেগুলো ফেরত দেয়</summary>
        public static HashSet<char> FindUnmapped(string converted)
        {
            HashSet<char> set = new HashSet<char>();
            foreach (char c in converted)
            {
                if (c < 0x80) continue;
                if (c >= '\u0980' && c <= '\u09FF') continue;
                if (c >= '\u2018' && c <= '\u201D') continue;
                if (c == '\u200C' || c == '\u200D' || c == '\u00A0') continue;
                set.Add(c);
            }
            return set;
        }
